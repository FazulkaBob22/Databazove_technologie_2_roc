\set ON_ERROR_STOP on
CREATE SCHEMA IF NOT EXISTS gold;

CREATE TABLE IF NOT EXISTS gold.sdim_day (
    day_id INT PRIMARY KEY,
    day INT NOT NULL,
    day_of_week VARCHAR(10) NOT NULL,
    UNIQUE (day, day_of_week)
);

CREATE TABLE IF NOT EXISTS gold.sdim_month (
    month_id INT PRIMARY KEY,
    month INT NOT NULL UNIQUE CHECK (month BETWEEN 1 AND 12),
    month_name VARCHAR(15) NOT NULL
);

CREATE TABLE IF NOT EXISTS gold.sdim_quarter (
    quarter_id INT PRIMARY KEY,
    quarter VARCHAR(2) NOT NULL UNIQUE,
    quarter_label VARCHAR(15) NOT NULL
);

CREATE TABLE IF NOT EXISTS gold.dim_date (
    date_id INT PRIMARY KEY,
    order_date DATE NOT NULL UNIQUE,
    day_id INT NOT NULL REFERENCES gold.sdim_day(day_id),
    week INT NOT NULL,
    month_id INT NOT NULL REFERENCES gold.sdim_month(month_id),
    year INT NOT NULL,
    quarter_id INT NOT NULL REFERENCES gold.sdim_quarter(quarter_id)
);

CREATE TABLE IF NOT EXISTS gold.sdim_category (
    category_id INT PRIMARY KEY,
    category_name VARCHAR(25)
);

CREATE TABLE IF NOT EXISTS gold.sdim_supplier (
    supplier_id INT PRIMARY KEY,
    supplier_name VARCHAR(50),
    address VARCHAR(50),
    city VARCHAR(50),
    country VARCHAR(15)
);

CREATE TABLE IF NOT EXISTS gold.dim_product (
    product_id INT PRIMARY KEY,
    product_name VARCHAR(50),
    product_unit VARCHAR(25),
    sdim_supplier_supplier_id INT REFERENCES gold.sdim_supplier(supplier_id),
    sdim_category_category_id INT REFERENCES gold.sdim_category(category_id)
);

CREATE TABLE IF NOT EXISTS gold.dim_shipper (
    shipper_id INT PRIMARY KEY,
    shipper_name VARCHAR(50)
);
CREATE TABLE IF NOT EXISTS gold.dim_employee (
    employee_id INT PRIMARY KEY,
    last_name VARCHAR(15),
    first_name VARCHAR(15)
);

CREATE TABLE IF NOT EXISTS gold.sdim_address (
    address_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    address VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS gold.sdim_city (
    city_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    city VARCHAR(20) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS gold.sdim_country (
    country_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    country VARCHAR(15) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS gold.dim_customer (
    customer_id INT PRIMARY KEY,
    customer_name VARCHAR(50),
    sdim_address_address_id INT REFERENCES gold.sdim_address(address_id),
    sdim_city_city_id INT REFERENCES gold.sdim_city(city_id),
    sdim_country_country_id INT REFERENCES gold.sdim_country(country_id)
);

CREATE TABLE IF NOT EXISTS gold.fact_order (
    order_detail_id INT PRIMARY KEY,
    order_id INT NOT NULL,
    quantity INT,
    price NUMERIC(10,2),
    date_id INT REFERENCES gold.dim_date(date_id),
    employee_id INT REFERENCES gold.dim_employee(employee_id),
    shipper_id INT REFERENCES gold.dim_shipper(shipper_id),
    product_id INT REFERENCES gold.dim_product(product_id),
    customer_id INT REFERENCES gold.dim_customer(customer_id)
);


CREATE INDEX ix_date_id ON gold.fact_order(date_id);
CREATE INDEX ix_employee_id ON gold.fact_order(employee_id);
CREATE INDEX ix_shipper_id ON gold.fact_order(shipper_id);
CREATE INDEX ix_product_id ON gold.fact_order(product_id);
CREATE INDEX ix_customer_id ON gold.fact_order(customer_id);
CREATE INDEX ix_order_id ON gold.fact_order(order_id);

BEGIN;

TRUNCATE TABLE
    gold.fact_order,
    gold.dim_date,
    gold.dim_customer,
    gold.dim_product,
    gold.dim_employee,
    gold.dim_shipper,
    gold.sdim_day,
    gold.sdim_month,
    gold.sdim_quarter,
    gold.sdim_category,
    gold.sdim_supplier,
    gold.sdim_address,
    gold.sdim_city,
    gold.sdim_country
RESTART IDENTITY;


INSERT INTO gold.sdim_day (day_id, day, day_of_week)
SELECT
    ROW_NUMBER() OVER (ORDER BY d.day, d.day_of_week)::INT,
    d.day,
    d.day_of_week
FROM (
    SELECT DISTINCT
        EXTRACT(DAY FROM order_date)::INT AS day,
        TO_CHAR(order_date, 'FMDay') AS day_of_week
    FROM silver.stg_orders
    WHERE order_date IS NOT NULL
) AS d;


INSERT INTO gold.sdim_month (month_id, month, month_name)
SELECT
    m AS month_id,
    m AS month,
    TO_CHAR(TO_DATE(m::TEXT, 'MM'), 'FMMonth') AS month_name
FROM GENERATE_SERIES(1, 12) AS m;

INSERT INTO gold.sdim_quarter (quarter_id, quarter, quarter_label)
SELECT
    q,
    'Q' || q::TEXT,
    'Quarter ' || q::TEXT
FROM GENERATE_SERIES(1, 4) AS q;



INSERT INTO gold.dim_date (
    date_id, order_date, day_id, week, month_id, year, quarter_id
)
SELECT
    TO_CHAR(o.order_date, 'YYYYMMDD')::INT AS date_id,
    o.order_date,
    dy.day_id,
    EXTRACT(WEEK FROM o.order_date)::INT AS week,
    EXTRACT(MONTH FROM o.order_date)::INT AS month_id,
    EXTRACT(YEAR FROM o.order_date)::INT AS year,
    EXTRACT(QUARTER FROM o.order_date)::INT AS quarter_id
FROM (
    SELECT DISTINCT order_date
    FROM silver.stg_orders
    WHERE order_date IS NOT NULL
) AS o
JOIN gold.sdim_day dy
  ON dy.day = EXTRACT(DAY FROM o.order_date)::INT
 AND dy.day_of_week = TO_CHAR(o.order_date, 'FMDay')
ORDER BY o.order_date;



INSERT INTO gold.sdim_category (category_id, category_name)
SELECT category_id, LEFT(category_name, 25)
FROM silver.stg_categories
WHERE category_id IS NOT NULL
ORDER BY category_id;
INSERT INTO gold.sdim_supplier (
    supplier_id, supplier_name, address, city, country
)
SELECT
    supplier_id,
    LEFT(supplier_name, 50),
    LEFT(address, 50),
    LEFT(city, 50),
    LEFT(country, 15)
FROM silver.stg_suppliers
WHERE supplier_id IS NOT NULL
ORDER BY supplier_id;


INSERT INTO gold.dim_product (
    product_id, product_name, product_unit,
    sdim_supplier_supplier_id, sdim_category_category_id
)
SELECT
    p.product_id,
    LEFT(p.product_name, 50),
    LEFT(p.product_unit, 25),
    p.supplier_id,
    p.category_id
FROM silver.stg_products p
WHERE p.product_id IS NOT NULL
ORDER BY p.product_id;


INSERT INTO gold.dim_shipper (shipper_id, shipper_name)
SELECT shipper_id, LEFT(shipper_name, 50)
FROM silver.stg_shippers
WHERE shipper_id IS NOT NULL
ORDER BY shipper_id;


INSERT INTO gold.dim_employee (employee_id, last_name, first_name)
SELECT
    employee_id,
    LEFT(last_name, 15),
    LEFT(first_name, 15)
FROM silver.stg_employees
WHERE employee_id IS NOT NULL
ORDER BY employee_id;


INSERT INTO gold.sdim_address (address)
SELECT DISTINCT LEFT(address, 50)
FROM silver.stg_customers
WHERE TRIM(address) IS NOT NULL
ORDER BY 1;

INSERT INTO gold.sdim_city (city)
SELECT DISTINCT LEFT(city, 20)
FROM silver.stg_customers
WHERE TRIM(city) IS NOT NULL
ORDER BY 1;

INSERT INTO gold.sdim_country (country)
SELECT DISTINCT LEFT(country, 15)
FROM silver.stg_customers
WHERE TRIM(country) IS NOT NULL
ORDER BY 1;


INSERT INTO gold.dim_customer (
    customer_id, customer_name,
    sdim_address_address_id, sdim_city_city_id, sdim_country_country_id
)
SELECT
    c.customer_id,
    LEFT(c.customer_name, 50),
    a.address_id,
    ci.city_id,
    co.country_id
FROM silver.stg_customers c
LEFT JOIN gold.sdim_address a
       ON a.address = LEFT(c.address, 50)
LEFT JOIN gold.sdim_city ci
       ON ci.city = LEFT(c.city, 20)
LEFT JOIN gold.sdim_country co
       ON co.country = LEFT(c.country, 15)
WHERE c.customer_id IS NOT NULL
ORDER BY c.customer_id;


INSERT INTO gold.fact_order (
    order_detail_id, order_id, quantity, price,
    date_id, employee_id, shipper_id, product_id, customer_id
)
SELECT
    od.order_detail_id,
    o.order_id,
    od.quantity,
    p.price,
    CASE
        WHEN o.order_date IS NOT NULL
        THEN TO_CHAR(o.order_date, 'YYYYMMDD')::INT
        ELSE NULL
    END AS date_id,
    o.employee_id,
    o.shipper_id,
    od.product_id,
    o.customer_id
FROM silver.stg_orderdetails od
JOIN silver.stg_orders o
  ON o.order_id = od.order_id
LEFT JOIN silver.stg_products p
  ON p.product_id = od.product_id
WHERE od.order_detail_id IS NOT NULL
ORDER BY od.order_detail_id;

COMMIT;